-- Apply after schema.sql (and seed.sql when migrating an existing project).
-- This migration is additive: legacy columns and JSON order items are retained
-- so existing reports and orders remain readable during rollout.

create table if not exists public.diseases (
  id bigint generated by default as identity primary key,
  legacy_slug text unique,
  name text not null unique,
  category text not null default '',
  description text not null default '',
  general_treatment text not null default '',
  affected_plant_parts text not null default '',
  growth_phase text not null default '',
  first_symptoms text not null default '',
  typical_causes text not null default '',
  more_info text not null default ''
);

insert into public.diseases (
  legacy_slug, name, category, description, general_treatment,
  affected_plant_parts, growth_phase, first_symptoms, typical_causes, more_info
)
select slug, name, category, short_description, typical_causes,
       affected_plant_parts, growth_phase, first_symptoms, typical_causes, more_info
from public.diagnosis_references
on conflict (legacy_slug) do update
set name = excluded.name,
    category = excluded.category,
    description = excluded.description,
    general_treatment = excluded.general_treatment,
    affected_plant_parts = excluded.affected_plant_parts,
    growth_phase = excluded.growth_phase,
    first_symptoms = excluded.first_symptoms,
    typical_causes = excluded.typical_causes,
    more_info = excluded.more_info;

create table if not exists public.symptoms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon_path text
);

create table if not exists public.disease_symptoms (
  disease_id bigint not null references public.diseases(id) on delete cascade,
  symptom_id bigint not null references public.symptoms(id) on delete cascade,
  primary key (disease_id, symptom_id)
);

insert into public.symptoms (name)
select distinct trim(symptom)
from public.diagnosis_references reference
cross join lateral regexp_split_to_table(reference.first_symptoms, ';') symptom
where trim(symptom) <> ''
on conflict (name) do nothing;

insert into public.disease_symptoms (disease_id, symptom_id)
select disease.id, symptom.id
from public.diagnosis_references reference
join public.diseases disease on disease.legacy_slug = reference.slug
cross join lateral regexp_split_to_table(reference.first_symptoms, ';') symptom_name
join public.symptoms symptom on symptom.name = trim(symptom_name)
where trim(symptom_name) <> ''
on conflict do nothing;

alter table public.reports
  add column if not exists disease_id bigint
    references public.diseases(id) on delete set null,
  add column if not exists adviser_id uuid
    references public.farmer_profiles(user_id) on delete set null;

update public.reports report
set disease_id = disease.id
from public.diseases disease
where report.disease_id is null
  and lower(trim(report.diagnosis)) = lower(trim(disease.name));

create table if not exists public.report_symptoms (
  report_id text not null references public.reports(id) on delete cascade,
  symptom_id bigint not null references public.symptoms(id) on delete restrict,
  primary key (report_id, symptom_id)
);

insert into public.report_symptoms (report_id, symptom_id)
select report.id, symptom.id
from public.reports report
cross join lateral regexp_split_to_table(report.description, E'[,\\n]+') item
join public.symptoms symptom on lower(trim(item)) = lower(symptom.name)
on conflict do nothing;

create table if not exists public.disease_medicines (
  disease_id bigint not null references public.diseases(id) on delete cascade,
  medicine_id bigint not null references public.products(id) on delete cascade,
  primary key (disease_id, medicine_id)
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.market_orders(id) on delete cascade,
  medicine_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price bigint not null check (unit_price >= 0),
  subtotal bigint generated always as (quantity * unit_price) stored
);

alter table public.market_orders
  add column if not exists report_id text
    references public.reports(id) on delete set null;

insert into public.order_items (
  order_id, medicine_id, product_name, quantity, unit_price
)
select
  order_row.id,
  nullif(item ->> 'product_id', '')::bigint,
  item ->> 'product_name',
  (item ->> 'quantity')::integer,
  (item ->> 'unit_price')::bigint
from public.market_orders order_row
cross join lateral jsonb_array_elements(order_row.items) item
where not exists (
  select 1 from public.order_items existing
  where existing.order_id = order_row.id
);

create table if not exists public.adviser_profiles (
  user_id uuid primary key references public.farmer_profiles(user_id)
    on delete cascade,
  certification_number text not null default '',
  institution text not null default ''
);

create table if not exists public.shop_profiles (
  user_id uuid primary key references public.farmer_profiles(user_id)
    on delete cascade,
  shop_name text not null default '',
  legality text not null default ''
);

insert into public.adviser_profiles (user_id)
select user_id from public.farmer_profiles where access_role = 'penyuluh'
on conflict (user_id) do nothing;

insert into public.shop_profiles (user_id, shop_name)
select user_id, name
from public.farmer_profiles
where access_role = 'mitra_toko'
on conflict (user_id) do nothing;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  report_id text references public.reports(id) on delete cascade,
  order_id text references public.market_orders(id) on delete cascade,
  message text not null,
  date timestamptz not null default now(),
  status_read boolean not null default false,
  check (report_id is not null or order_id is not null)
);

create index if not exists report_symptoms_symptom_idx
  on public.report_symptoms(symptom_id);
create index if not exists disease_symptoms_symptom_idx
  on public.disease_symptoms(symptom_id);
create index if not exists order_items_order_idx
  on public.order_items(order_id);
create index if not exists notifications_user_date_idx
  on public.notifications(user_id, date desc);

