create or replace function public.notify_report_activity()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.notifications (user_id, report_id, message)
    select user_id, new.id, 'Laporan baru menunggu peninjauan.'
    from public.farmer_profiles
    where access_role = 'penyuluh';
  elsif new.status is distinct from old.status then
    insert into public.notifications (user_id, report_id, message)
    values (new.owner_id, new.id, 'Status laporan diperbarui: ' || new.status);
  end if;
  return new;
end;
$$;

drop trigger if exists notify_report_activity on public.reports;
create trigger notify_report_activity
  after insert or update of status on public.reports
  for each row execute procedure public.notify_report_activity();

create or replace function public.notify_order_activity()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.notifications (user_id, order_id, message)
    select user_id, new.id, 'Pesanan baru menunggu diproses.'
    from public.farmer_profiles
    where access_role = 'mitra_toko';
  elsif new.status is distinct from old.status then
    insert into public.notifications (user_id, order_id, message)
    values (new.customer_id, new.id, 'Status pesanan diperbarui: ' || new.status);
  end if;
  return new;
end;
$$;

