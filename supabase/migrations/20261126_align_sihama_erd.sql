  for each row execute procedure public.notify_order_activity();

create or replace function public.place_market_order(
  p_order_id text,
  p_report_id text,
  p_customer_name text,
  p_customer_phone text,
  p_delivery_address text,
  p_items jsonb,
  p_transfer_proof_path text
)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_items jsonb := '[]'::jsonb;
  v_total bigint := 0;
  v_proof_prefix text;
  v_report public.reports%rowtype;
begin
  if auth.uid() is null
     or public.current_access_role() is distinct from 'pelapor' then
    raise exception 'Hanya pelapor yang dapat membuat pesanan.';
  end if;
  select * into v_report
  from public.reports
  where id = p_report_id
    and owner_id = auth.uid()
    and status = 'Selesai Ditinjau';
  if not found then
    raise exception 'Pilih laporan Anda yang sudah selesai ditinjau.';
  end if;
  if nullif(trim(p_order_id), '') is null then
    raise exception 'ID pesanan tidak valid.';
  end if;
  if nullif(trim(p_customer_name), '') is null
     or nullif(trim(p_customer_phone), '') is null
     or nullif(trim(p_delivery_address), '') is null then
    raise exception 'Nama, kontak, dan alamat wajib diisi.';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Pesanan harus berisi minimal satu produk.';
  end if;
  v_proof_prefix := 'orders/' || auth.uid()::text || '/';
  if p_transfer_proof_path is null
     or left(p_transfer_proof_path, length(v_proof_prefix)) <> v_proof_prefix then
    raise exception 'Bukti transfer tidak valid.';
  end if;
  if not exists (
    select 1 from storage.objects
    where bucket_id = 'sihama-media' and name = p_transfer_proof_path
  ) then
    raise exception 'Bukti transfer belum tersimpan.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item ->> 'product_id', '') !~ '^[0-9]+$'
       or coalesce(v_item ->> 'quantity', '') !~ '^[0-9]+$' then
      raise exception 'Rincian produk pesanan tidak valid.';
    end if;
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 then
      raise exception 'Jumlah produk harus lebih dari nol.';
    end if;
    select * into v_product
    from public.products
    where id = (v_item ->> 'product_id')::bigint
    for update;
    if not found or v_product.stock < v_quantity then
      raise exception 'Stok produk tidak mencukupi.';
    end if;
    update public.products
    set stock = stock - v_quantity
    where id = v_product.id;
    v_total := v_total + (v_product.price * v_quantity);
    v_items := v_items || jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id,
      'product_name', v_product.name,
      'quantity', v_quantity,
      'unit_price', v_product.price
    ));
  end loop;

  insert into public.market_orders (
    id, report_id, customer_id, customer_name, customer_phone,
    delivery_address, status, items, total, transfer_proof_path
  ) values (
    p_order_id, p_report_id, auth.uid(), trim(p_customer_name),
    trim(p_customer_phone), trim(p_delivery_address), 'Dipesan',
    v_items, v_total, p_transfer_proof_path
  );

  insert into public.order_items (
    order_id, medicine_id, product_name, quantity, unit_price
  )
  select p_order_id,
         (item ->> 'product_id')::bigint,
         item ->> 'product_name',
         (item ->> 'quantity')::integer,
         (item ->> 'unit_price')::bigint
  from jsonb_array_elements(v_items) item;
end;
$$;

