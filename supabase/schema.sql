create or replace function public.update_market_order_status(
  p_order_id text,
  p_next_status text
)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_order public.market_orders%rowtype;
begin
  if auth.uid() is null
     or public.current_access_role() is distinct from 'mitra_toko' then
    raise exception 'Hanya mitra toko yang dapat memperbarui status pesanan.';
  end if;

  select * into v_order
  from public.market_orders
  where id = p_order_id
  for update;
  if not found then
    raise exception 'Pesanan tidak ditemukan.';
  end if;

  if not (
    (v_order.status = 'Dipesan' and p_next_status in ('Diproses', 'Dibatalkan'))
    or (v_order.status = 'Diproses' and p_next_status in ('Dikirim', 'Dibatalkan'))
    or (v_order.status = 'Dikirim' and p_next_status = 'Selesai')
  ) then
    raise exception 'Perubahan status pesanan tidak valid.';
  end if;

  if p_next_status = 'Dibatalkan' then
    update public.products p
    set stock = p.stock + item.quantity
    from (
      select
        (value ->> 'product_id')::bigint as product_id,
        sum((value ->> 'quantity')::integer)::integer as quantity
      from jsonb_array_elements(v_order.items)
      group by (value ->> 'product_id')::bigint
    ) item
    where p.id = item.product_id;
  end if;

  update public.market_orders
  set status = p_next_status
  where id = p_order_id;
end;
$$;

revoke all on function public.update_market_order_status(text, text)
  from public, anon;
grant execute on function public.update_market_order_status(text, text)
  to authenticated;

create or replace function public.delete_current_account()
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception 'Tidak ada akun yang sedang masuk.';
  end if;
  delete from public.products where created_by = auth.uid();
  delete from storage.objects
  where bucket_id = 'sihama-media'
    and split_part(name, '/', 2) = auth.uid()::text;
  delete from auth.users where id = auth.uid();
end;
$$;

