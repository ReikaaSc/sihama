create table if not exists public.farmer_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null default '',
  role text not null default 'Petani',
  access_role text not null default 'pelapor'
    check (access_role in ('pelapor', 'penyuluh', 'mitra_toko')),
  region text not null default '',
  phone text not null default '',
  address text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id text primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  crop text not null,
  location text not null,
  description text not null,
  date timestamptz not null,
  status text not null default 'Diajukan',
  photo_path text,
  diagnosis text,
  recommendation text
);

create table if not exists public.diagnosis_references (
  slug text primary key,
  name text not null,
  category text not null,
  short_description text not null default '',
  affected_plant_parts text not null default '',
  growth_phase text not null default '',
  first_symptoms text not null default '',
  typical_causes text not null default '',
  more_info text not null default ''
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  created_by uuid references auth.users(id) on delete set null,
  name text not null,
  category text not null,
  price bigint not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  description text not null default '',
  photo_path text
);

create table if not exists public.market_orders (
  id text primary key,
  customer_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null,
  date timestamptz not null default now(),
  status text not null default 'Dipesan'
    check (status in ('Dipesan', 'Diproses', 'Dikirim', 'Selesai', 'Dibatalkan')),
  items jsonb not null,
  total bigint not null check (total >= 0),
  transfer_proof_path text not null
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  report_id text not null references public.reports(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_role text not null,
  sender_name text not null,
  message text not null,
  sent_at timestamptz not null default now()
);

