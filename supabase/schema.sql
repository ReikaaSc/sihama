create or replace function public.set_chat_sender_identity()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_profile public.farmer_profiles%rowtype;
begin
  select * into v_profile
  from public.farmer_profiles
  where user_id = auth.uid();
  if not found then
    raise exception 'Profil pengguna tidak ditemukan.';
  end if;
  new.sender_id := auth.uid();
  new.sender_name := v_profile.name;
  new.sender_role := case v_profile.access_role
    when 'penyuluh' then 'Penyuluh'
    when 'mitra_toko' then 'Mitra Toko'
    else 'Pelapor'
  end;
  return new;
end;
$$;

drop trigger if exists set_chat_sender_identity on public.chat_messages;
create trigger set_chat_sender_identity
  before insert on public.chat_messages
  for each row execute procedure public.set_chat_sender_identity();

create or replace function public.protect_report_review_fields()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if public.current_access_role() is distinct from 'penyuluh'
     and (
       new.status is distinct from old.status
       or new.diagnosis is distinct from old.diagnosis
       or new.recommendation is distinct from old.recommendation
     ) then
    raise exception 'Hanya penyuluh yang dapat meninjau laporan.';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_report_review_fields on public.reports;
create trigger protect_report_review_fields
  before update on public.reports
  for each row execute procedure public.protect_report_review_fields();

